// LQR balance controller for the upright Furuta pendulum.
//
// Full state feedback with a constant gain row K:
//
//   u = -K * x          (equilibrium: upright, x = 0, torque 0)
//
// State  x = [theta, alpha, theta_dot, alpha_dot]   (alpha = 0 is upright)
// Output u = arm torque [N.m], saturated to +-TAU_MAX
//
// K comes from a discrete-time LQR (dlqr) on the linearised upright model,
// discretised with a zero-order hold at TS. It assumes compute() is called
// exactly once per TS.
//
// The state weights Q and input weight R used for the design are withheld in
// this public version. The gain is generated by the MATLAB design script;
// retune the weights there and regenerate rather than editing K by hand.
#pragma once
#include <Eigen/Dense>

namespace furuta
{

class Controller_LQR
{
  public:
    static constexpr int NX = 4;
    using StateVec = Eigen::Matrix<float, NX, 1>;
    using GainVec = Eigen::Matrix<float, 1, NX>;

    static constexpr float TAU_MAX = 5.0f; // torque limit [N.m]
    static constexpr float U_EQ = 0.0f;    // equilibrium torque [N.m]
    static constexpr float TS = 0.005f;    // sample time K was designed for [s]

    // Saturated arm torque.
    float compute(const StateVec& x) const
    {
        const float u = computeRaw(x);
        return u > TAU_MAX ? TAU_MAX : (u < -TAU_MAX ? -TAU_MAX : u);
    }

    // Torque before saturation.
    float computeRaw(const StateVec& x) const
    {
        return -(K() * x)(0, 0) + U_EQ;
    }

  private:
    static const GainVec& K()
    {
        static const GainVec k = (GainVec() << -0.0427574301f, 0.764022192f, -0.0352383142f, 0.0905118955f).finished();
        return k;
    }
};

} // namespace furuta
